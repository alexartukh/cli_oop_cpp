#pragma once

// Тело шаблонных функций обязано находиться здесь, в заголовке (а не в Utils.cpp) —
// компилятор генерирует конкретную версию (например, Max<Decimal>) только в том
// файле, где одновременно видит и объявление, и полное определение шаблона.
// Если оставить определение в .cpp, любой другой файл, вызывающий Max/Min,
// увидит только объявление — и компоновщик не найдёт скомпилированную функцию
template<typename T>
T Max(T a, T b)
{
    return (a > b) ? a : b;
}

template<typename T>
T Min(T a, T b)
{
    return (a < b) ? a : b;
}
